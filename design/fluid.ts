// Ported unchanged from picture-perfect-pets/design/fluid.ts: fluid clamp() helpers, WCAG contrast and the tokens.css generator.
import {
  breakpoints,
  fixed,
  palette,
  semantic,
  spacePairs,
  spaceScale,
  typeScale,
  viewport,
} from "./tokens";

const round = (n: number) => Number(n.toFixed(4));

// clamp(min, intercept + slope·vw, max) that grows linearly from the min to the max viewport.
export function fluid(minRem: number, maxRem: number) {
  if (minRem === maxRem) return `${round(minRem)}rem`;
  const slope = (maxRem - minRem) / (viewport.max - viewport.min);
  const intercept = minRem - slope * viewport.min;
  const lo = Math.min(minRem, maxRem);
  const hi = Math.max(minRem, maxRem);
  return `clamp(${round(lo)}rem, ${round(intercept)}rem + ${round(slope * 100)}vw, ${round(hi)}rem)`;
}

export function typeStep(step: number) {
  const { base, ratio } = typeScale;
  return fluid(base.min * ratio.min ** step, base.max * ratio.max ** step);
}

export function spaceStep(key: keyof typeof spaceScale) {
  const m = spaceScale[key];
  return fluid(typeScale.base.min * m, typeScale.base.max * m);
}

export function spacePair(a: keyof typeof spaceScale, b: keyof typeof spaceScale) {
  return fluid(typeScale.base.min * spaceScale[a], typeScale.base.max * spaceScale[b]);
}

// WCAG 2.x relative luminance and contrast ratio.
function luminance(hex: string) {
  const n = hex.replace("#", "");
  const [r = 0, g = 0, b = 0] = [0, 2, 4].map((i) => {
    const c = parseInt(n.slice(i, i + 2), 16) / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}
export function contrast(a: string, b: string) {
  const [hi = 0, lo = 0] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

const stepName = (s: number) => (s < 0 ? `-${Math.abs(s)}` : String(s));

// The generated stylesheet. Kept in one function so the CI check can diff it.
export function tokensCss() {
  const lines: string[] = [
    "/* Generated by `npm run tokens` from design/tokens.ts. Do not edit. */",
    "@layer reset, tokens, base, layout, components, patterns, utilities;",
    "",
    "@layer tokens {",
    "  :root {",
  ];
  const push = (name: string, value: string) => lines.push(`    --${name}: ${value};`);
  lines.push("    /* Primitive palette */");
  for (const [ramp, shades] of Object.entries(palette)) {
    if (typeof shades === "string") push(`${ramp}`, shades);
    else for (const [shade, hex] of Object.entries(shades)) push(`${ramp}-${shade}`, hex);
  }
  lines.push("    /* Fluid type scale (rem) */");
  for (const s of typeScale.steps) push(`step-${stepName(s)}`, typeStep(s));
  lines.push("    /* Fluid space scale (rem) */");
  for (const key of Object.keys(spaceScale) as Array<keyof typeof spaceScale>)
    push(`space-${key}`, spaceStep(key));
  for (const [a, b] of spacePairs) push(`space-${a}-${b}`, spacePair(a, b));
  lines.push("    /* Fixed tokens */");
  for (const [k, v] of Object.entries(fixed)) push(k, v);
  lines.push("    /* Semantic colours (light) */");
  lines.push("    color-scheme: light;");
  for (const [k, v] of Object.entries(semantic.light)) push(`color-${k}`, v);
  lines.push("  }");
  const dark = Object.entries(semantic.dark)
    .map(([k, v]) => `    --color-${k}: ${v};`)
    .join("\n");
  lines.push(
    "",
    "  @media (prefers-color-scheme: dark) {",
    "    :root:not([data-theme=\"light\"]) {",
    "      color-scheme: dark;",
    dark.replaceAll("\n    ", "\n      ").replace(/^ {4}/, "      "),
    "    }",
    "  }",
    "  :root[data-theme=\"dark\"] {",
    "    color-scheme: dark;",
    dark,
    "  }",
    "}",
    "",
    `/* Breakpoints: ${Object.entries(breakpoints)
      .map(([k, v]) => `${k} ${v}`)
      .join(" · ")} (use in @media as min-width: <value>) */`,
    "",
  );
  return lines.join("\n");
}
